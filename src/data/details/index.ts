import { frameworkDetails } from "./frameworks";
import { mentalModelDetails } from "./mental-models";
import { uxLawDetails } from "./ux-laws";
import type { ContentDetail } from "./types";

export type { Application, ContentDetail } from "./types";

const details: Record<string, ContentDetail> = {
  ...uxLawDetails,
  ...frameworkDetails,
  ...mentalModelDetails,
};

/**
 * The long-form content for a card.
 *
 * Throws rather than returning null so that a card added without its detail
 * content fails the build, instead of shipping an empty page: every id in
 * src/data/* is statically generated by /[contentId].
 */
export function getContentDetail(id: string): ContentDetail {
  const detail = details[id];
  if (!detail) {
    throw new Error(`No detail content for "${id}". Add it to src/data/details.`);
  }
  return detail;
}
